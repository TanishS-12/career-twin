import os
from dotenv import load_dotenv
from google import genai
import json

# Load environment variables from .env file
# This allows us to keep sensitive configuration outside the Python source code
load_dotenv()
api_key = os.getenv("GEMINI_API_KEY")
gemini_model = os.getenv("GEMINI_MODEL")

# Validate the Gemini API key is available before creating the Gemini client
if not api_key:
    raise ValueError("GEMINI_API_KEY is not configured")

# Create the Gemini API client
client = genai.Client(api_key=api_key)

# Define the generation configuration
# max_output_tokens: Limits the max amount of output generated by Gemini
# thinking_level: controls the amount of model reasoning effort used for the request
generation_config = {
    'max_output_tokens': 2000,
    'thinking_level': 'medium',
}


# Define the exact JSON sctructure that Gemini must return
career_analysis_schema = {
    "type": "object",
    "properties": {
        "profile_summary": {
            "type": "string",
            "description": "A concise summary of the student's current profile"
        },
        "strengths": {
            "type": "array",
            "items": {
                "type": "string"
            },
            "description": "Technical or career strengths identified from profile"
        },
        "skill_gaps": {
            "type": "array",
            "items": {
                "type": "string"
            },
            "description": "Skills missing or insufficient for the target role"
        },
        "priority_skills": {
            "type": "array",
            "items": {
                "type": "string"
            },
            "description": "Skills that student should prioritize"
        },
        "interview_topics": {
            "type": "array",
            "items": {
                "type": "string"
            },
            "description": "Topics the student should prepare for interviews"
        }
    },
    "required": [
        "profile_summary",
        "strengths",
        "skill_gaps",
        "priority_skills",
        "interview_topics",
    ]
}


